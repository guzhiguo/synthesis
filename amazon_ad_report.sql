-- 亚马逊广告报告数据表
CREATE TABLE IF NOT EXISTS `amazon_ad_report` (
    `id`                    BIGINT(20)   NOT NULL AUTO_INCREMENT COMMENT '主键',
    `report_date`           DATE         DEFAULT NULL COMMENT '日期',
    `portfolio_name`        VARCHAR(255) DEFAULT NULL COMMENT '广告组合名称',
    `currency`              VARCHAR(16)  DEFAULT NULL COMMENT '货币',
    `campaign_name`         VARCHAR(512) DEFAULT NULL COMMENT '广告活动名称',
    `ad_group_name`         VARCHAR(512) DEFAULT NULL COMMENT '广告组名称',
    `retailer`              VARCHAR(128) DEFAULT NULL COMMENT '零售商',
    `country`               VARCHAR(64)  DEFAULT NULL COMMENT '国家/地区',
    `placement`             VARCHAR(128) DEFAULT NULL COMMENT '投放',
    `match_type`            VARCHAR(128) DEFAULT NULL COMMENT '匹配类型',
    `search_term`           VARCHAR(512) DEFAULT NULL COMMENT '客户搜索词',
    `impressions`           INT(11)      DEFAULT 0  COMMENT '展示量',
    `clicks`                INT(11)      DEFAULT 0  COMMENT '点击量',
    `ctr`                   VARCHAR(32)  DEFAULT NULL COMMENT '点击率(CTR)',
    `cpc`                   DECIMAL(12,4) DEFAULT 0 COMMENT '单次点击成本(CPC)',
    `spend`                 DECIMAL(12,4) DEFAULT 0 COMMENT '花费',
    `sales_7d`              DECIMAL(12,4) DEFAULT 0 COMMENT '7天总销售额',
    `acos`                  VARCHAR(32)  DEFAULT NULL COMMENT '广告投入产出比(ACOS)',
    `roas`                  VARCHAR(32)  DEFAULT NULL COMMENT '总广告投资回报率(ROAS)',
    `orders_7d`             INT(11)      DEFAULT 0  COMMENT '7天总订单数',
    `units_7d`              INT(11)      DEFAULT 0  COMMENT '7天总销售量',
    `conversion_rate_7d`    VARCHAR(32)  DEFAULT NULL COMMENT '7天的转化率',
    `ad_sku_units_7d`       INT(11)      DEFAULT 0  COMMENT '7天内广告SKU销售量',
    `other_sku_units_7d`    INT(11)      DEFAULT 0  COMMENT '7天内其他SKU销售量',
    `ad_sku_sales_7d`       DECIMAL(12,4) DEFAULT 0 COMMENT '7天内广告SKU销售额',
    `other_sku_sales_7d`    DECIMAL(12,4) DEFAULT 0 COMMENT '7天内其他SKU销售额',
    `gmt_create`            DATETIME     DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `gmt_modify`            DATETIME     DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '修改时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_date_term_campaign_group` (`report_date`, `search_term`(100), `campaign_name`(100), `ad_group_name`(100)),
    KEY `idx_report_date` (`report_date`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='亚马逊广告报告原始数据';
